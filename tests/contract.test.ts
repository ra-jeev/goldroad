import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { apiContracts, checkContract } from '../scripts/generate-contract';

const root = fileURLToPath(new URL('../contract/', import.meta.url));

describe('GoldRoad contract', () => {
  it('matches outputs generated by the web source', () => {
    checkContract(root);
  });

  for (const [name, { schema }] of Object.entries(apiContracts)) {
    it(`validates the committed ${name} API sample`, () => {
      const value: unknown = JSON.parse(readFileSync(join(root, 'api', 'samples', `${name}.json`), 'utf8'));
      const result = schema.safeParse(value);
      expect(result.success, result.error?.message).toBe(true);
    });
  }
});
